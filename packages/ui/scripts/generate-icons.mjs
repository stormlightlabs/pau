import { readFile, writeFile } from 'node:fs/promises';

import { createGenerator } from '@unocss/core';

import config from '../uno.config.ts';

const outputUrl = new URL('../src/styles/icons.css', import.meta.url);
const generator = await createGenerator(config);
const source = await readFile(new URL('../src/icons.ts', import.meta.url), 'utf8');
const { css } = await generator.generate(source, { preflights: false });

if (!css.trim()) throw new Error('UnoCSS did not generate any icons from src/icons.ts');

const output = `/* Generated by \`pnpm icons:generate\`. Do not edit directly. */\n${css}\n`;

if (process.argv.includes('--check')) {
	let current = '';
	try {
		current = await readFile(outputUrl, 'utf8');
	} catch {
		// A missing output file is reported as stale below.
	}
	if (current !== output) {
		throw new Error('Generated icon CSS is stale. Run `pnpm --filter @stormlightlabs/pau-ui icons:generate`.');
	}
} else {
	await writeFile(outputUrl, output);
}
